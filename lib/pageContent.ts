/** 허브 경로별 하위 섹션 슬러그 목록 (generateStaticParams 용) */
export function sectionsOf(base: string) {
  return Object.keys(pageContent)
    .filter((p) => p.startsWith(`${base}/`))
    .map((p) => p.slice(base.length + 1));
}
