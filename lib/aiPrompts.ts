export const jobOf = (id: string) => aiJobs.find((j) => j.id === id) ?? null;

/** 과목 탭을 세우는 업무인가 — 과목을 받아야 어느 과목의 요구사항을 붙일지 고를 수 있다 */
export const bySubject = (job: AiJob) => job.vars.some((v) => v.key === "{{과목}}");

/* 자리표 안의 띄어쓰기는 fill()처럼 봐준다 — {{ 과목요구사항 }}도 같은 자리다.
   g 깃발 정규식은 lastIndex를 들고 다니므로 쓸 때마다 새로 만든다 */
const slotRe = () => /\{\{\s*과목요구사항\s*\}\}/g;
/** 자리표와 그 앞뒤 빈칸 — 빈 자리를 걷을 때 쓴다 */
const slotAroundRe = () => /(\s*)\{\{\s*과목요구사항\s*\}\}(\s*)/g;

/** 과목 요구사항 자리표를 기준으로 가른다. 조각이 하나면 자리표가 없는 프롬프트다 */
export const splitAtSlot = (prompt: string) => prompt.split(slotRe());

/** 과목 요구사항 한 절. 적은 것이 없으면 빈 글 — 제목만 남은 절을 보내지 않는다 */
export function subjectSection(subject: PromptSubject, extra?: SubjectExtra): string {
  const body = extra?.[subject]?.trim() ?? "";
  return body ? `${subject} 요구사항\n${body}` : "";
}

/**
 * 한 과목의 프롬프트를 조립한다 — 호출 직전에 부르는 자리.
 *
 * subject가 null이면(기본 탭) 자리표만 걷는다. 자리표가 없는 프롬프트는 맨 끝에 붙인다.
 *
 * 빈 자리는 자리표와 그 둘레의 빈칸을 함께 걷고, 앞뒤 빈칸 가운데 넓은 쪽 하나만 남긴다 —
 * 문단 사이에 있던 자리면 문단 사이가, 문장 가운데 있던 자리면 띄어쓰기 하나가 남고, 글
 * 머리나 끝이면 아무것도 남지 않는다. 자리표 둘레 밖은 건드리지 않는다. 운영자가 일부러
 * 벌려 둔 줄까지 접으면 기본 탭에서 쓴 글과 실제로 나가는 글이 달라진다.
 *
 * ⚠ 요구사항을 넣을 때 replace()를 쓰지 않는다. 적은 글에 $&가 들어 있으면 치환 기호로 읽힌다.
 */
export function withSubject(
  prompt: string,
  subject: PromptSubject | null,
  extra?: SubjectExtra,
): string {
  const section = subject ? subjectSection(subject, extra) : "";
  const parts = splitAtSlot(prompt);
  if (parts.length === 1) return section ? `${prompt.trimEnd()}\n\n${section}` : prompt;
  if (section) return parts.join(section);
  const lines = (w: string) => w.split("\n").length;
  return prompt.replace(slotAroundRe(), (m, lead: string, trail: string, at: number, all: string) => {
    if (at === 0 || at + m.length === all.length) return "";
    if (lines(lead) !== lines(trail)) return lines(lead) > lines(trail) ? lead : trail;
    return lead.length >= trail.length ? lead : trail;
  });
}

