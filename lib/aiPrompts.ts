/** 글에서 자리표를 뽑는다 */
export function varsIn(text: string): string[] {
  const out: string[] = [];
  const re = /\{\{\s*([^}]+?)\s*\}\}/g;
  let hit: RegExpExecArray | null;
  while ((hit = re.exec(text)) !== null) out.push(`{{${hit[1]}}}`);
  return out;
}

/**
 * 자리표를 채운다.
 *
 * 상수({{상수.…}})는 실제로 걸려 있는 값이라 언제나 채운다(lib/aiPromptConsts.ts). 나머지는
 * 본보기 값이라 예시로 돌릴 때만 채운다 — 손으로 적어 두면 저쪽 상수를 고친 날 화면이 옛
 * 숫자를 말하는 데서 그치지 않고 모델도 옛 숫자로 돈다.
 */
export function fill(
  text: string,
  consts: Record<string, string>,
  withSamples: boolean,
): string {
  return text.replace(/\{\{\s*([^}]+?)\s*\}\}/g, (m, name: string) => {
    const key = `{{${name.trim()}}}`;
    if (consts[key]) return consts[key];
    if (withSamples && sampleVars[key]) return sampleVars[key];
    return m;
  });
}
