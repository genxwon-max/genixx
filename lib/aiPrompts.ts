  href?: string;
  where?: string;
  /** 서버가 프롬프트에 채워 넣는 값 */
  vars: PromptVar[];
  /** 상세를 처음 열었을 때 들어 있는 AI 하나 */
  seed: AiJobSeed;
  /** 예시로 돌릴 때 첫 AI에 들어가는 것 */
