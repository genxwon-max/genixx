/** 글 토막 — 그냥 글자이거나, 밑줄이 그어질 구절이다 */
export type Seg = string | { t: string; mark: number };

export type TryMark = {
  kind: MarkKind;
  /** 밑줄에 붙는 이름표 */
  label: string;
  /** 이 자리에서 무엇이 보이는가 */
  why: string;
};

export type TryChoice = {
  text: string;
  /** 고르고 나면 뜨는 한 줄 — 맞고 틀림이 아니라 어떻게 읽었는지를 적는다 */
  note: string;
};

export type TryItem = {
  id: string;
  subject: SubjectId;
  level: Level;
  axis: AxisId;
  material: { label: string; title: string; paras: Seg[][] };
  stem: Seg[];
  choices: TryChoice[];
  /** 0부터 */
  answer: number;
  /** 밑줄 이름표 — Seg의 mark 번호가 이 배열의 자리다 */
  marks: TryMark[];
  /** 오른쪽에서 밀려 나오는 간단 진단서에 실을 것 */
  report: {
    /** 이 한 문항에서 보이는 것 세 줄 */
    reads: { kind: MarkKind; t: string; d: string }[];
    right: string;
    wrong: string;
    next: string[];
  };
};

