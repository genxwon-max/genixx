/**
 * 부를 수 있는 모델 목록 (ADM-13-1).
 *
 * 「어떤 AI를 쓰는가」는 프롬프트만큼이나 산출물을 바꾼다. 같은 지시를 줘도 무거운 모델은
 * 오답지에 오개념을 심고 가벼운 모델은 그럴듯한 낱말만 바꿔 놓는다. 그런데 여태 이 값이
 * 어디에도 없어서, 문항이 이상할 때 「무엇을 시켰나」는 물어도 「누구에게 시켰나」는 물을
 * 자리가 없었다.
 *
 * ── 고르는 것과 잠그는 것 ──
 * 모델과 호출 값(창의성·최대 길이)은 **연다.** 잘못 골라도 산출물이 나빠질 뿐이고, 나빠진
 * 것은 검수와 채점 검토에서 사람이 잡는다 — 여는 칸을 가른 기준과 같다.
 *
 * 키와 엔드포인트는 **여전히 가린다.** 저것은 고르는 값이 아니라 비밀이고, 화면에 한 번
 * 내려오면 「가렸다」가 개발자 도구 앞에서 거짓이 된다. 바꾸는 자리는 시스템 설정(ADM-13)이다.
 *
 * ── 목록이 코드인 까닭 ──
 * 모델을 하나 늘리는 일은 값 하나를 고르는 일이 아니라 **붙이는 일**이다. 호출 형식과 값
 * 범위와 요금이 따라오고, 그 셋을 모르는 채로 이름만 늘리면 고른 순간 호출이 깨진다. 그래서
 * 고르는 것은 데이터이고 목록은 코드다 — 늘리려면 이 파일을 고쳐 배포한다.
 *
 * ⚠ 이 콘솔은 아직 모델을 부르지 않는다. 여기 고른 값은 붙일 때 그대로 넘어갈 값이다.
 *
 * ⚠ 지시자("use client")를 붙이지 않는다. 씨앗(lib/aiPrompts.ts)이 이 목록을 읽고, 그 씨앗은
 *   서버 조각도 읽을 수 있어야 한다.
 */

