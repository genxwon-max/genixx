export const textbookUnits: TextbookUnit[] = SUBJECTS.flatMap((subject) =>
  (Object.entries(RAW[subject]) as [TermKey, Entry[]][]).flatMap(([term, entries]) => {
    const [g, t] = term.split("-").map(Number);
    let no = 0;
    return entries.map((e): TextbookUnit => {
      const base = { subject, grade: g as TextbookUnit["grade"], term: t as TextbookUnit["term"] };
      if (typeof e !== "string") return { ...base, no: null, kind: e[0], title: e[1] };
      no += 1;
      return { ...base, no, title: e };
    });
  }),
);

/** 「3-1」 */
export const termOf = (u: Pick<TextbookUnit, "grade" | "term">) => `${u.grade}-${u.term}`;

/** 고르개의 값 — 같은 이름이 학기마다 있어서(수학 「분수의 나눗셈」) 이름만으로는 못 가린다 */
export const unitKey = (u: TextbookUnit) => `${u.subject}|${termOf(u)}|${u.title}`;

/** 「국어 - 생생하게 표현해요」 */
export const unitLabel = (u: Pick<TextbookUnit, "subject" | "title">) =>
  `${u.subject} - ${u.title}`;

/** 「1단원」 · 「독서 단원」 */
export const unitPlace = (u: TextbookUnit) => (u.no === null ? `${u.kind} 단원` : `${u.no}단원`);

/** 문항에 적는 단원 번호 — 두 자리. 번호 없는 단원은 비운다 */
export const unitNoOf = (u: TextbookUnit) => (u.no === null ? "" : String(u.no).padStart(2, "0"));

/**
 * 어느 학년의 단원을 볼 것인가 — 학년군(옛 콘솔)이나 학년 하나(새 콘솔).
 *
 * 새 콘솔은 학년을 하나씩 고른다. 3학년 문항의 고르개에 4학년 단원까지 서 있으면 학년을 따로
 * 고른 뜻이 없어진다.
 *
 * ⚠ 1·2학년 교과서 단원은 아직 옮기지 않았다. 그 학년은 목록이 비고, 단원 칸이 손으로 적는
 *   칸으로 바뀐다(BandUnitRows).
 */
export type UnitScope = GradeBand | GradeNo;

const scopeGrades = (scope: UnitScope): number[] =>
  typeof scope === "number"
    ? [scope]
    : scope === "1-2"
      ? [1, 2]
      : scope === "3-4"
        ? [3, 4]
        : scope === "5-6"
          ? [5, 6]
          : scope === "7-9"
            ? [7, 8, 9]
            : [10, 11, 12];

/** 학년에 드는 단원 — 과목 → 학년 → 학기 → 교과서 차례 */
export function unitsForBand(scope: UnitScope): TextbookUnit[] {
  const grades = scopeGrades(scope);
  return textbookUnits.filter((u) => grades.includes(u.grade));
}

/** 고르개의 묶음 — 「국어 · 3학년 1학기」마다 한 덩이 */
export function unitGroups(scope: UnitScope) {
  const groups: { label: string; units: TextbookUnit[] }[] = [];
  for (const u of unitsForBand(scope)) {
    const label = `${u.subject} · ${u.grade}학년 ${u.term}학기`;
    const last = groups[groups.length - 1];
    if (last?.label === label) last.units.push(u);
    else groups.push({ label, units: [u] });
  }
  return groups;
}

/**
 * 문항에 적힌 단원이 목록의 어느 단원인가. 목록 밖이면 null.
 *
 * 목록에서 고른 문항은 과목 · 학년-학기 · 이름이 모두 같아야 찾은 것으로 본다. 번호로 찾지
 * 않는다 — 교과서가 바뀌어 같은 번호에 다른 단원이 들어서면, 번호로 찾아 새 이름을 붙여 주는
 * 순간 출제위원이 고른 적 없는 단원이 문항에 붙는다. 이름이 달라졌으면 목록 밖으로 세워 다시
 * 고르게 한다.
 *
 * 고르개가 생기기 전의 문항(학년-학기 없음)은 과목과 이름으로만 찾는다.
 */
export function findUnit(
  item: { subject: string; unit: string; unitNo: string; unitTerm: string },
  scope: UnitScope,
): TextbookUnit | null {
  const title = item.unit.trim();
  if (!title) return null;
  const same = unitsForBand(scope).filter((u) => u.subject === item.subject && u.title === title);
  if (item.unitTerm) return same.find((u) => termOf(u) === item.unitTerm) ?? null;
  /* 학년-학기가 없는 옛 문항. 같은 이름이 여러 학기에 있으면(수학 「분수의 나눗셈」) 짐작하지
     않는다 — 짐작한 학년·학기를 옆에 적어 두면 고른 것으로 읽혀 아무도 다시 고르지 않는다.
     적어 둔 단원 번호로 하나가 가려질 때만 그것으로 본다 */
  if (same.length === 1) return same[0];
  const byNo = same.filter((u) => u.no !== null && u.no === Number(item.unitNo));
  return byNo.length === 1 ? byNo[0] : null;
}

