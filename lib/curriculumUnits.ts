/**
 * 단원이 다루는 성취기준 — 문항 상세에서 학년 · 교과 단원을 고르면 첫 코드가 성취기준 코드 칸에 들어간다
 * (lib/itemStore.ts withUnitStandard).
 *
 * 과학은 표 없이 셈한다. 교과서 단원이 2022 개정 과학과 교육과정의 주제 순서를 한 학기에 넷씩 그대로
 * 따르므로(BASIS) 3학년 1학기 1단원이 [4과01], 4학년 1학기 2단원이 [4과10]이다. 주제 안의 몇 번째
 * 성취기준인지는 문항마다 달라 첫 번째(-01)를 넣고, 출제위원이 고쳐 쓴다.
 */
export function standardsOfUnit(u: TextbookUnit): UnitStandard[] {
  if (u.subject === "과학") {
    if (u.no === null) return [];
    const topic = (u.grade % 2 === 0 ? 8 : 0) + (u.term - 1) * 4 + u.no;
    const band = u.grade <= 4 ? 4 : 6;
    return [{ code: `[${band}과${String(topic).padStart(2, "0")}-01]` }];
  }
  return (UNIT_CODES[unitKey(u)] ?? []).map((c) => ({ code: `[${c}]`, text: STANDARD_TEXT[c] }));
}
