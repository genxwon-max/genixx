/*
 * EXP-08 리포트 승인 — 조립된 리포트를 확인하고 보호자에게 내보낸다.
 *
 * 이 서비스가 파는 것은 「사람이 확정한 판정」이고, 그 약속이 코드로 서 있는 자리가 여기다 —
 * **발행 전에는 보호자 화면에 결과가 보이지 않는다.** 조립은 규칙이 하고, 내보내는 것은
 * 사람이 한다.
 *
 * ── 평가를 마친 회원만 선다 ──
 * 리포트는 응시가 끝나야 조립되므로(lib/reportStore.ts의 ensureReport) 이 목록에 있다는
 * 것이 곧 「평가를 마쳤다」는 뜻이다. 아직 안 본 아이는 여기 아예 없어서 따로 거를 것이 없다.
 *
 * ── 왜 예약이 필요한가 ──
 * 회차가 끝나면 리포트가 한꺼번에 쏟아진다. 다 확인하고 한날에 보내면 그날 문의가 몰려
 * 고객지원이 막히고, 하나씩 보내면 「누구까지 보냈더라」를 사람이 외워야 한다. 날짜를 걸어
 * 두면 확인은 오늘 하고 나가는 것은 나눠 나간다. 1주일 뒤·2주 뒤를 단추로 둔 것은 실제로
 * 쓰는 간격이 그 둘이기 때문이고, 그 밖의 날은 날짜 칸에서 직접 고른다.
 *
 * ⚠ 예약을 이 콘솔이 지키지는 않는다. 날짜가 되면 저절로 나가는 일은 서버가 할 일이고
 *   여기는 그 날짜를 적어 두는 자리다. 지금은 때가 지난 것을 목록이 맨 위에 세워 사람이
 *   누르게 한다.
 *
 * ⚠ 보내는 것과 발행은 같은 일이다. 보호자 화면이 열리는 순간이 곧 보낸 순간이라
 *   lib/reportSendStore.ts의 sendNow가 둘을 함께 한다.
 *
 * ⚠ 라벨링 점검에 막는 말이 있으면 발행이 거부된다(헌장 7조). 그런 줄은 보내기가 잠기고
 *   목록에 「점검」으로 선다 — 눌러 놓고 아무 일도 안 일어나는 줄을 만들지 않는다.
 */
