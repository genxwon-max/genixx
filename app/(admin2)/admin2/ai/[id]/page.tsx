import AiJobDetail from "./AiJobDetail";

export const metadata = { title: "AI 프롬프트 상세" };

/*
 * ADM-13-1 AI 프롬프트 상세 — 한 업무에 서는 AI들의 프롬프트를 고치는 자리.
 *
 * ── 판 하나에 AI 하나 ──
 * 위에서 아래로 도는 차례가 곧 화면의 차례다. 탭으로 갈라 두었다가 되돌렸다 — 탭은 한 번에
 * 하나만 보여 주므로 「1번이 낸 것이 2번에 들어간다」는 이 화면의 요점이 화면에서 사라졌다.
 * 세로로 이어 두면 그 흐름이 스크롤 방향과 같아진다.
 *
 * ── 과목 탭은 다른 축이다 ──
 * {{과목}}을 받는 업무에는 기본 · 국어 · 수학 · 과학 탭이 선다. 위에서 걷어 낸 탭은 AI를
 * 가른 것이고, 이 탭은 과목을 가른다 — 어느 탭에서든 AI들은 여전히 세로로 이어져 있다.
 * 기본 탭이 흐름을 짜고, 과목 탭은 AI마다 그 과목에만 붙일 요구사항을 적는다
 * (국어 — 문제에 숫자가 나오지 않게, 과학 — 문제에 영어가 나오지 않게).
 *
 * ── 고칠 수 있는 것 ──
 * 이름 · 프롬프트 · 모델 · 붙이는 파일, 그리고 과목 요구사항이다.
 *
 * 출력 형식·윤리 규칙·연결 키는 이 화면에 올리지 않는다. 서버가 호출할 때 붙인다 — 보여 주지
 * 않으면 고칠 수도, 새어 나갈 수도 없다.
 *
 * ⚠ 자리표({{학년}} 같은 것)는 접어 둔다. 프롬프트를 쓸 때만 필요한 목록이고, 늘 펴 두면
 *   판이 두 배가 된다. 필수 자리표가 빠진 채로는 저장이 막힌다 — {{학생답안}} 없이 나간 채점
 *   프롬프트는 답안을 못 본 채로 점수를 매기고, 그 사실은 산출물에서야 드러난다.
 *
 * ⚠ 업무마다 key를 준다. 같은 경로 꼴 안에서 업무만 갈아 끼우면 React가 조각을 그대로 두어,
 *   앞 업무에 치던 글이 다음 업무 화면에 그대로 남는다.
 */
export default async function Admin2AiJobPage({ params }: PageProps<"/admin2/ai/[id]">) {
  const { id } = await params;
  return <AiJobDetail key={id} id={id} />;
}
